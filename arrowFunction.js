//arrow function
const calc = function (num) {
  return num * 5;
};
console.log(calc(10));

const calclate = (num) => {
  return num * 3;
};
console.log(calclate(3));

const calclatenew = (num) => num * 100;
console.log(calclatenew(3));

const add = (a, b) => a + b;
console.log(add(5, 9));

const hello = () => "hello";
console.log(hello())
